#include <assert.h>
#include <c4rt3/c4rt.h>

#include "internal_type.h"

c4_datum_type
c4_datum_type_of(const c4_datum datum) {
	const c4_datum_type type = datum->type;
	assert(type <= C4_Nil && "type out of range");
	assert(type != 2 && "blackholeeeeeeeeee....");

	return type;
}
